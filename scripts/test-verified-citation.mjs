import assert from 'node:assert/strict';
import { repair, NEW, ID } from './repair-verified-citation.mjs';
const old = 'https://pacificwrecks.com/airfields/philippines/nichols/1945/aerial-manila-nichols-nielson.html?fbclid=IwAR2677HbJdytkeZhCzBI3E51UNGFTk3CC1VI_Z6bXcq3BotXFGbBTrJ1El0';
const credit = 'Aerial view of Nichols Field and Nielson Field from B-24 after bombing attack, 1945, USAAF, FEAF.';
const note = '<li id="' + ID + '">' + credit + ' Retrieved on May 6, 2023, from: <a href="' + old + '" target="_blank" rel="noreferrer noopener">Original label</a> <a href="#' + ID + '-link">↩</a></li>';
const html = '<meta name="robots" content="noindex,nofollow"><section data-chm-restored-footnotes="1"><ol>' + note + '</ol></section>';
let n = 0;
const ok = f => { f(); n++; };
ok(() => { const fixed = repair(html); assert.equal(fixed, html.replace(old, NEW)); assert.equal(repair(fixed), fixed); assert.equal(repair(fixed, true), fixed); });
ok(() => assert.throws(() => repair(html, true), /obsolete/));
ok(() => assert.throws(() => repair(html.replace('noindex,nofollow', 'index,follow')), /noindex/));
ok(() => assert.throws(() => repair(html.replace('data-chm-restored-footnotes="1"', 'data-other="1"')), /restored/));
ok(() => assert.throws(() => repair(html.replace(ID, 'other-id')), /count/));
ok(() => assert.throws(() => repair(html.replace(note, note + note)), /count/));
ok(() => assert.throws(() => repair(html.replace(credit, 'Other photograph')), /credit/));
ok(() => assert.throws(() => repair(html.replace(old, old.replace('nichols', 'wrong'))), /unrecognized/));
ok(() => assert.throws(() => repair(html.replace(old, old.replace('fbclid=', 'download='))), /unrecognized/));
ok(() => assert.throws(() => repair(html.replace(old, 'https://example.org/unrelated')), /publisher link/));
ok(() => assert.throws(() => repair(html.replace('</li>', '')), /closing/));
ok(() => assert.ok(repair(html + '<a href="https://pacificwrecks.com/other">Other source</a>').includes('href="https://pacificwrecks.com/other"')));
console.log('Publisher citation regression assertions:', n, 'PASS');
